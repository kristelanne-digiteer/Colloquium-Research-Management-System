import { useState } from 'react';
import { Send, TriangleAlert } from 'lucide-react';
import Modal from '../common/modal';
import ChairButton from './chairButton';
import { useChair } from '../../context/chairContext';

const field =
  'w-full rounded-xl border border-secondary-300 bg-white px-3.5 py-2.5 text-sm text-slate-900 focus:border-primary-500 focus:outline-none focus:ring-2 focus:ring-primary-500/40 read-only:bg-secondary-50 dark:border-secondary-700 dark:bg-secondary-800 dark:text-slate-100 dark:read-only:bg-secondary-800/60';
const label = 'mb-1.5 block text-xs font-semibold text-secondary-500';

// Render with key={paper.id} so the draft resets for every paper.
export default function EmailModal({ paper, onClose }) {
  const { chairName, notify } = useChair();
  const locked = paper.reviewsDone < 2;
  const recipient = `${paper.author} <author@ethics-portal.org>`;

  const [subject, setSubject] = useState(
    locked ? '[LOCKED] Pending Review Threshold' : `Ethics Committee Decision: ${paper.id} - ${paper.status}`
  );
  const [body, setBody] = useState(
    locked
      ? `Official decision emails require at least 2 completed reviewer evaluations. Current progress: ${paper.reviewsDone}/${paper.reviewsTotal}.`
      : `Dear ${paper.author},\n\nWe have completed the ethical review for your manuscript titled "${paper.title}".\n\nOfficial Decision: ${paper.status.toUpperCase()}\nReview Consensus: ${paper.consensus}\n\nPlease review formal documentation generated by the EC Chair Portal.\n\nBest regards,\n${chairName}\nChair, Ethics Committee`
  );

  const send = () => {
    notify(`Official email dispatched to ${recipient}.`);
    onClose();
  };

  return (
    <Modal
      open
      onClose={onClose}
      icon={Send}
      title="Send Automated Decision Email"
      subtitle={`Paper ID: ${paper.id}`}
      footer={
        <>
          <ChairButton variant="secondary" onClick={onClose}>Cancel</ChairButton>
          <ChairButton icon={Send} onClick={send} disabled={locked}>Send Email</ChairButton>
        </>
      }
    >
      {locked && (
        <div className="mb-4 flex items-start gap-2 rounded-xl bg-amber-50 px-3.5 py-3 text-sm text-amber-800 dark:bg-amber-900/20 dark:text-amber-300">
          <TriangleAlert className="mt-0.5 h-4 w-4 flex-shrink-0" />
          <span>Automated dispatch is locked until at least 2 reviewer evaluations are submitted.</span>
        </div>
      )}
      <div className="space-y-4">
        <div>
          <label className={label}>Recipient Author</label>
          <input className={field} value={recipient} readOnly />
        </div>
        <div>
          <label className={label}>Email Subject</label>
          <input className={field} value={subject} onChange={(e) => setSubject(e.target.value)} readOnly={locked} />
        </div>
        <div>
          <label className={label}>Email Message Body</label>
          <textarea
            rows={8}
            className={field}
            value={body}
            onChange={(e) => setBody(e.target.value)}
            readOnly={locked}
          />
        </div>
      </div>
    </Modal>
  );
}
